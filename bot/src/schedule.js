const TRENES = (() => {
  const out = {};
  for (const dia of Object.keys(TRENES_RAW)) {
    out[dia] = {};
    for (const sentido of Object.keys(TRENES_RAW[dia])) {
      const paso = sentido === "m" ? 1 : -1;
      out[dia][sentido] = TRENES_RAW[dia][sentido].map(([n, first, ini, deltas]) => {
        const t = new Array(16).fill(null);
        let id = first;
        let min = ini;
        t[id] = min;
        for (const d of deltas) {
          id += paso;
          min += d;
          t[id] = min;
        }
        return { n, first, t };
      });
    }
  }
  return out;
})();

